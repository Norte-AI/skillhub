import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from '../apps/server/src/index.mjs';

test('real store issues revocable device tokens and keeps session bindings immutable', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'skillhub-http-device-'));
  const events = [];
  const app = await createServer({ dataDir, token: 'admin-test', logger: event => events.push(event) });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await rm(dataDir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const call = (path, body, token = 'admin-test', method = body === undefined ? 'GET' : 'POST') => fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const json = async (path, body) => { const response = await call(path, body); assert.ok(response.ok, await response.clone().text()); return response.json(); };
  await json('/api/content', { id: 'rule', title: 'Rule', kind: 'rule', body: 'Keep a version marker.' });
  for (const id of ['assigned', 'private']) await json('/api/bundles', { id, name: id, items: ['rule'] });
  const release = await json('/api/releases', { bundleId: 'assigned', version: '1.0.0' });
  const duplicate = await call('/api/releases', { bundleId: 'assigned', version: '1.0.0' }); assert.equal(duplicate.status, 409);
  await json('/api/channels', { bundleId: 'assigned', channel: 'stable', releaseId: release.id, expectedGeneration: 0 });
  assert.equal((await call('/api/channels', { bundleId: 'assigned', channel: 'stable', releaseId: release.id, expectedGeneration: 0 })).status, 409);
  await json('/api/devices', { id: 'dev', name: 'Test device', client: 'codex', assignments: ['assigned'] });
  const issuance = await call('/api/devices/dev/token', undefined, 'admin-test', 'POST'); assert.equal(issuance.status, 201);
  const { token } = await issuance.json(); assert.match(token, /^shd_/);
  const devices = await json('/api/devices'); assert.equal('tokenHash' in devices[0], false); assert.equal('token' in devices[0], false);
  assert.deepEqual((await (await call('/api/bundles', undefined, token)).json()).map(b => b.id), ['assigned']);
  const session = { id: 's', releaseIds: [release.id] };
  assert.equal((await call('/api/sessions', session, token)).status, 201);
  assert.equal((await call('/api/sessions', { ...session, deviceId: 'different' }, token)).status, 403);
  const receipt = { id: 'receipt', sessionId: 's', releaseId: release.id, kind: 'installed', source: 'trusted', trusted: true, evidence: 'Test file digest.' };
  const response = await call('/api/receipts', receipt, token); assert.equal(response.status, 201);
  const saved = await response.json(); assert.equal(saved.trusted, false); assert.equal(saved.source, 'client-reported');
  assert.equal((await call('/api/receipts', { ...receipt, evidence: 'Changed.' }, token)).status, 409);
  assert.equal((await call('/api/audit', undefined, token)).status, 403);
  const audit = await json('/api/audit');
  assert.deepEqual(audit.find(event => event.action === 'device.token-issued').actor, { role: 'admin' });
  assert.deepEqual(audit.find(event => event.action === 'receipt.reported').actor, { role: 'device', deviceId: 'dev' });
  assert.equal((await call('/api/releases/not-here')).status, 404);
  assert.equal((await call('/api/devices/dev/revoke', undefined, 'admin-test', 'POST')).status, 200);
  assert.equal((await call('/api/bundles', undefined, token)).status, 401);
  assert.ok(events.every(event => typeof event.requestId === 'string' && !JSON.stringify(event).includes(token)));
  assert.ok(response.headers.get('x-request-id'));
});
