import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from '../apps/server/src/index.mjs';
const upload = { id: 'submission', contentId: 'writing', body: '---\nname: writing\ndescription: Help with writing\n---\nWrite clearly.' };
test('HTTP skill submission, review, publication gate and access restrictions', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'hub-review-http-'));
  const app = await createServer({ dataDir, authenticate: async req => req.headers.authorization === 'Bearer admin' ? { role: 'admin' } : req.headers.authorization === 'Bearer device' ? { role: 'device', deviceId: 'device' } : null });
  await app.store.registerDevice({ id: 'device', name: 'Device', client: 'codex' });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await rm(dataDir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}`;
  const call = (path, data, role = 'admin') => fetch(base + path, { method: data ? 'POST' : 'GET', headers: { Authorization: `Bearer ${role}`, 'Content-Type': 'application/json' }, ...(data ? { body: JSON.stringify(data) } : {}) });
  assert.equal((await call('/api/submissions', undefined, 'none')).status, 401);
  assert.equal((await call('/api/submissions', upload, 'device')).status, 403);
  const pendingResponse = await call('/api/submissions', upload);
  assert.equal(pendingResponse.status, 201);
  assert.equal((await pendingResponse.json()).status, 'pending');
  assert.equal((await (await call('/api/content')).json()).length, 0);
  assert.equal((await (await call('/api/submissions?status=pending')).json()).length, 1);
  assert.equal((await call('/api/submissions/submission', undefined, 'device')).status, 403);
  const approvedResponse = await call('/api/submissions/submission/reviews', { decision: 'approve', comment: 'Instructions reviewed' });
  assert.equal(approvedResponse.status, 200);
  assert.equal((await approvedResponse.json()).status, 'approved');
  assert.equal((await call('/api/submissions/submission/reviews', { decision: 'reject', comment: 'Again' })).status, 409);
  assert.equal((await call('/api/bundles', { id: 'personal', name: 'Personal', items: ['writing'] })).status, 201);
  const releaseResponse = await call('/api/releases', { bundleId: 'personal', version: '1.0.0' });
  assert.equal(releaseResponse.status, 201);
  const release = await releaseResponse.json();
  await call('/api/content', { id: 'writing', kind: 'skill', title: 'Bypass', body: 'Unreviewed' });
  assert.equal((await call('/api/releases', { bundleId: 'personal', version: '1.0.1' })).status, 403);
  assert.equal((await (await call(`/api/releases/${release.id}`)).json()).items[0].revision, 1);
});
